/**
 * Build an icon element.
 *
 * @param doc - The document to create the element in.
 * @param name - Which icon.
 * @returns The SVG element, sized to the current font.
 */
export function iconSvg(doc: Document, name: SelectionIconName): SVGSVGElement {
  const svg = doc.createElementNS("http://www.w3.org/2000/svg", "svg");
  svg.setAttribute("viewBox", "0 0 24 24");
  svg.setAttribute("width", "15");
  svg.setAttribute("height", "15");
  svg.setAttribute("fill", "none");
  svg.setAttribute("stroke", "currentColor");
  svg.setAttribute("stroke-width", "2");
  svg.setAttribute("stroke-linecap", "round");
  svg.setAttribute("stroke-linejoin", "round");
  svg.classList.add("inscribe-icon");
  svg.innerHTML = ICONS[name];
  return svg;
}
